import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const baseUrl = process.env.WEB_BASE_URL;
if (!baseUrl) { console.log('AIZAN behavior skipped: WEB_BASE_URL is not set'); process.exit(0); }
const browser=await chromium.launch(process.env.CHROMIUM_EXECUTABLE_PATH ? {executablePath:process.env.CHROMIUM_EXECUTABLE_PATH,args:['--no-sandbox']} : {});
const page=await browser.newPage({viewport:{width:390,height:845},ignoreHTTPSErrors:process.env.WEB_TEST_IGNORE_HTTPS_ERRORS === "1"});
await page.route('**/api/v1/**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'API unavailable in behavior test'})}));
await page.addInitScript(()=>{
 localStorage.setItem('ai-lawyer-web-state',JSON.stringify({view:'home',theme:'dark',authUserId:'test-user',profileComplete:true,caseText:'Мой сохранённый текст обращения',cases:[],documents:[]}));
 Object.defineProperty(navigator,'mediaDevices',{value:{getUserMedia:()=>Promise.reject(new DOMException('Denied','NotAllowedError'))},configurable:true});
});
await page.goto(baseUrl.replace(/\/$/, '') + '/#home');await page.waitForTimeout(200);
await page.getByRole('button',{name:'Ввести текст',exact:true}).click();
await page.locator('.aizanHomeComposer textarea').waitFor();
assert.equal(await page.locator('.aizanHomeComposer textarea').inputValue(),'Мой сохранённый текст обращения');
assert.equal(await page.locator('.appShell').getAttribute('data-view'),'home');
await page.route('**/api/v1/ai/classifications', route => route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({id:'test-classification',result:{category_label:'Трудовой спор',subcategory_label:'Заработная плата',clarification_questions:[{questionRu:'За какой период не выплачена зарплата?'}],missing_facts:['period']}})}));
await page.getByRole('button',{name:'Отправить',exact:true}).click();
await page.getByText('Трудовой спор: Заработная плата. За какой период не выплачена зарплата?',{exact:true}).waitFor();
assert.equal(await page.locator('.appShell').getAttribute('data-view'),'home');
assert.equal(await page.locator('.bottomNav').isVisible(),true);
for (const width of [320,390,1024]) {
 await page.setViewportSize({width,height:845});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 2));
}
await page.setViewportSize({width:390,height:845});
await page.getByRole('button',{name:'Рассказать проблему',exact:true}).click();
await page.locator('.aizanFeedback').waitFor();
assert.match(await page.locator('.aizanFeedback').innerText(),/Микрофон недоступен/);
assert.equal(await page.locator('.aizanHomeComposer textarea').inputValue(),'Мой сохранённый текст обращения');
assert.equal(await page.locator('.appShell').getAttribute('data-view'),'home');
await page.getByRole('button',{name:'Новое дело',exact:true}).click();
assert.equal(await page.locator('.aizanHomeComposer textarea').inputValue(),'');
await page.locator('.bottomNav').getByRole('button',{name:'Документы',exact:true}).click();
await page.getByRole('button',{name:'Шаблоны',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Шаблоны',exact:true}).getAttribute('class'),'active');
assert.equal(await page.locator('.nativeUploadControl input[type=file]').count(),2);
const authPage = await browser.newPage({viewport:{width:390,height:845},ignoreHTTPSErrors:process.env.WEB_TEST_IGNORE_HTTPS_ERRORS === "1"});
await authPage.goto(baseUrl);
const phone = authPage.locator('.loginExactPhone input');
await phone.waitFor();
await phone.pressSequentially('7011234567');
assert.equal(await phone.inputValue(), '7011234567');
await authPage.getByRole('button',{name:'Получить SMS-код',exact:true}).click();
const modalPhone = authPage.locator('.authExactField input').first();
await modalPhone.waitFor();
assert.equal(await modalPhone.inputValue(), '+77011234567');
await modalPhone.fill('+7');
await modalPhone.pressSequentially('7771234567');
assert.equal(await modalPhone.inputValue(), '+77771234567');
await modalPhone.press('Backspace');
assert.equal(await modalPhone.inputValue(), '+7777123456');
await modalPhone.fill('87011234567');
assert.equal(await modalPhone.inputValue(), '+77011234567');
await browser.close();
console.log('AIZAN behavior: phone typing/deletion/paste stable; text and voice stay on home; text preserved, microphone denial visible, explicit new draft resets text, document tabs/native file inputs work');
