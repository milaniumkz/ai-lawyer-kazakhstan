export function buildGeneratedClients(spec) {
  const paths = Object.keys(spec.paths).sort();
  const ts = `// Generated by scripts/contracts/generate-clients.mjs\nexport const apiPaths = ${JSON.stringify(paths, null, 2)} as const;\nexport type ApiPath = (typeof apiPaths)[number];\nexport const apiBasePath = '/api/v1' as const;\n`;
  const dart = `// Generated by scripts/contracts/generate-clients.mjs\nabstract final class ApiContract {\n  static const basePath = '/api/v1';\n${paths.map((path) => `  static const ${toDartName(path)} = '${path}';`).join('\n')}\n}\n`;
  return { paths, ts, dart };
}

function toDartName(path) {
  const clean = path
    .replace(/[{}]/g, '')
    .split('/')
    .filter(Boolean)
    .map((part, index) => {
      const normalized = part.replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => char.toUpperCase());
      return index === 0 ? normalized : normalized[0].toUpperCase() + normalized.slice(1);
    })
    .join('');
  return clean || 'root';
}
